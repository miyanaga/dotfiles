#!/usr/bin/env bash
# ワーカーモードを解除して、普段使いのMacに戻す（worker/setup.sh の逆）。
#
#   ./worker/setdown.sh          適用して検証（何度実行しても安全）
#   ./worker/setdown.sh --check  適用せず、現在値が期待どおりかの検証だけ
#   ./worker/setdown.sh --yes    確認プロンプトを飛ばす
#
# root権限が要るため、--check でもsudoのパスワードを聞かれる。
#
# ■ 戻すもの
#     - リモートログイン(SSH) …… OFF
#     - 画面共有 …………………… OFF
#     - FileVault解除後の自動ログイン抑止 … 解除（macOS既定に戻す）
#     - スクリーンセーバ ………… macOS既定（20分）に戻す
#     - 画面オフ …………………… 10分（macos/defaults.sh の値）
#     - 停電復帰後の自動起動 …… OFF
#     - macOS自動アップデート …… ON
#
# ■ 戻さないもの（意図的）
#     - FileVault ………… ONのまま。解除する理由がない
#     - 自動ログイン …… OFFのまま。利便性のために無防備な起動に戻す意味はない
#     - 即時ロック ……… そのまま
#
#   電源設定の戻し先は macOS の工場出荷値ではなく **macos/defaults.sh の値**
#   （AC接続時は本体スリープなし・画面のみ10分でオフ）。2つのスクリプトが
#   同じ項目を取り合わないようにするため。
#
# ■ 注意
#   画面共有で接続したまま実行すると、その接続自体が切れる。
#   切れた後は物理的にMacの前に座らないと戻せないので、実行前に確認を求める。
set -euo pipefail

MODE=off

epilogue() {
  cat <<EOF
============================================================
ワーカーモードを解除しました。

  SSHと画面共有は無効です。再びリモート運用するなら:
    ./worker/setup.sh

  FileVault・自動ログインOFF・即時ロックはそのまま維持しています。
  普段使い機としての設定は  ./macos/defaults.sh  が基準です。
============================================================
EOF
}

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"
